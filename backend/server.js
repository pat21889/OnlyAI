const path = require("path");
const express = require("express");
const dotenv = require("dotenv");
const cookieParser = require("cookie-parser");
const helmet = require("helmet");
const rateLimit = require("express-rate-limit");
const hpp = require("hpp");
const swaggerJsDoc = require("swagger-jsdoc");
const swaggerUI = require("swagger-ui-express");
const cors = require("cors");
const connectDB = require("./config/db");
const auth = require("./routes/auth");
const facilities = require("./routes/facilities");
const bookings = require("./routes/bookings");

dotenv.config({ path: path.join(__dirname, "config/config.env") });

if (process.env.MONGO_URI) {
  connectDB().catch((error) => {
    console.error(`Database connection failed: ${error.message}`);
    // On Vercel, exiting kills the function before it can send any (CORS-headed) response.
    if (!process.env.VERCEL) process.exit(1);
  });
}

const app = express();

// Vercel sits behind a proxy; needed so rate limiting sees the real client IP.
app.set("trust proxy", 1);
app.use(helmet());
app.use(hpp());
app.use(rateLimit({
  windowMs: 10 * 60 * 1000,
  limit: 100,
  message: {
    success: false,
    error: "Too many requests from this IP, please try again later.",
  },
}));
app.use(express.json({ limit: "10mb" }));
app.use(express.urlencoded({ extended: true, limit: "10mb" }));
app.use(cookieParser());
app.use(cors({
  origin: process.env.FRONTEND_URL || "http://localhost:3000",
  credentials: true,
}));

if (process.env.MONGO_URI) {
  app.use((req, res, next) => connectDB().then(() => next(), next));
}

app.use("/api/v1/auth", auth);
app.use("/api/v1/facilities", facilities);
app.use("/api/v1/bookings", bookings);

const swaggerDocs = swaggerJsDoc({
  definition: {
    openapi: "3.0.0",
    info: {
      title: "Sports Facility Booking API",
      version: "1.0.0",
      description: "REST API for sports facility management and bookings.",
    },
    servers: [{ url: "/" }],
    components: {
      securitySchemes: {
        bearerAuth: {
          type: "http",
          scheme: "bearer",
          bearerFormat: "JWT",
        },
      },
    },
  },
  apis: [path.join(__dirname, "routes/*.js"), __filename],
});

app.use("/api-docs", swaggerUI.serve, swaggerUI.setup(swaggerDocs));

app.get("/health", (req, res) => {
  res.status(200).json({
    success: true,
    message: "Sports Facility Booking API is running",
    timestamp: new Date().toISOString(),
    environment: process.env.NODE_ENV || "development",
  });
});

app.get("/", (req, res) => {
  res.status(200).json({
    success: true,
    message: "Welcome to the Sports Facility Booking API",
    documentation: "/api-docs",
    health: "/health",
  });
});

app.use((req, res) => {
  res.status(404).json({
    success: false,
    error: `Route ${req.originalUrl} not found`,
  });
});

app.use((err, req, res, next) => {
  console.error(err.stack);
  res.status(err.statusCode || 500).json({
    success: false,
    error: err.message || "Internal Server Error",
    ...(process.env.NODE_ENV === "development" ? { stack: err.stack } : {}),
  });
});

// On Vercel the platform runs the exported app; only listen when run locally.
if (!process.env.VERCEL) {
  const PORT = process.env.PORT || 5000;
  const server = app.listen(PORT, () => {
    console.log(`Sports Facility Booking API running on http://localhost:${PORT}`);
  });

  process.on("unhandledRejection", (error) => {
    console.error(`Unhandled rejection: ${error.message}`);
    server.close(() => process.exit(1));
  });

  process.on("uncaughtException", (error) => {
    console.error(`Uncaught exception: ${error.message}`);
    process.exit(1);
  });
}

module.exports = app;
